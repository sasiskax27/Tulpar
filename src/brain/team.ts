// 🤖 Команда агентов: Кодер → Тестировщик → Ревьюер по очереди решают одну задачу.
import { executeCommand } from "../commands/registry";
import { askInput } from "../app/InputBox";

export async function runTeam() {
  const task = await askInput({ title: "Задача для команды ИИ", placeholder: "Например: «добавь страницу входа с проверкой пароля»" });
  if (!task?.trim()) return;
  await executeCommand("workbench.action.chat.open");
  const chat = await import("../ai/chat");
  chat.setAgentMode(true);
  const prompt = [
    `Задача: ${task.trim()}`,
    "",
    "Работай как команда из трёх ролей, строго по очереди, и начинай каждый этап с заголовка:",
    "## 👨‍💻 Кодер — изучи проект и реализуй задачу небольшими правками.",
    "## 🧪 Тестировщик — напиши или обнови тесты для изменений и запусти их (или собери проект, если тестов нет). Если что-то упало — верни работу кодеру и исправь.",
    "## 🔍 Ревьюер — перечитай все изменённые файлы как строгий старший разработчик: баги, безопасность, читаемость. Исправь найденное сам.",
    "## ✅ Итог — коротко: что сделано, какие файлы изменены, что проверено.",
  ].join("\n");
  void chat.send(prompt);
}
